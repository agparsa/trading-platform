export type Locale = 'en' | 'fa';

export const MESSAGES: Readonly<Record<Locale, Messages>> = { en, fa };

export type Translate = (
  key: MessageKey,
  vars?: Readonly<Record<string, string | number>>,
) => string;

/** A message with `{name}` placeholders filled. A missing value stays visible as `{name}`. */
export function translate(
  locale: Locale,
  key: MessageKey,
  vars?: Readonly<Record<string, string | number>>,
): string {
  const template = MESSAGES[locale][key];
  if (vars === undefined) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    vars[name] === undefined ? whole : String(vars[name]),
  );
}

/** The English translator: the default for logic modules, and what their tests read. */
export const english: Translate = (key, vars) => translate('en', key, vars);

/** A key for a server refusal code, when there are words for it. */
export function errorKey(code: string | undefined): MessageKey | null {
  if (code === undefined) return null;
  const key = `err.${code}`;
  return key in en ? (key as MessageKey) : null;
}

/** The device's language when it is one the app speaks; English otherwise. */
export function deviceLocale(tag: string | null | undefined): Locale {
  return tag !== null && tag !== undefined && tag.toLowerCase().startsWith('fa') ? 'fa' : 'en';
}

/**
 * What to show for a refusal: the server's code in the reader's words when
 * there are some, the server's own message otherwise, and `fallback` when the
 * failure never reached the server.
 */
export function refusalText(caught: unknown, fallback: MessageKey, t: Translate): string {
  if (typeof caught === 'object' && caught !== null && 'code' in caught && 'message' in caught) {
    const { code, message } = caught as { code: unknown; message: unknown };
    return serverWords(typeof code === 'string' ? code : undefined, String(message), t);
  }
  return t(fallback);
}

/**
 * A refusal the server sent, in the reader's language.
 *
 * The server writes English, and its message carries the specifics — "A BUY
 * stop loss must sit below 4584.6". In English that message is the best one.
 * In Persian the code's sentence comes first and the server's message follows,
 * so the number is not lost — the web terminal's rule.
 */
export function serverWords(code: string | undefined, message: string, t: Translate): string {
  const key = errorKey(code);
  const persian = t('meta.locale') === 'fa';
  if (key === null || !persian) return message.trim() === '' && key !== null ? t(key) : message;
  return message.trim() === '' ? t(key) : `${t(key)} — ${message}`;
}
